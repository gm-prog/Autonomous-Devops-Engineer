"""Phase 8.7-D.1-CORRECTION-3 (Finding E) — dependency parity guard.

The audit found the CI test environment (fastapi 0.128.8 / starlette 0.52.1
/ anyio 4.12.1) and the container image (fastapi 0.143.0 / starlette 1.7.0 /
anyio 4.15.1, from broad ``>=`` ranges) had drifted apart: security was
tested on one dependency set and shipped on another.

This guard inspects the ACTUAL files and fails CI when:

* the hash-pinned locks (``requirements-runtime.txt`` /
  ``requirements-test.txt``) are missing, were not generated by
  ``pip-compile --generate-hashes``, or a pinned package lacks hashes;
* the two locks DISAGREE on any shared package version (the "one
  compatible set" contract: test == container for every shared package);
* the runtime lock is missing any of the 14 declared direct runtime
  dependencies, or the test lock is missing its test-only tools;
* any service Dockerfile (gateway, agent, deployment production + E2E)
  does NOT install the runtime lock with ``pip install --require-hashes``;
* any CI Python job installs without ``--require-hashes`` (the unpinned
  fallback the audit flagged), or the retired broad ``requirements.txt``
  reappears.

Mutation M29 reintroduces drift (a shared pin changed in one lock, or
``--require-hashes`` dropped from a Dockerfile) and must turn this guard
red.

Run standalone with the other guards:

    PYTHONPATH=devops-ai-platform python -m security_guards
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, List

PLATFORM = "devops-ai-platform"
RUNTIME_IN = f"{PLATFORM}/requirements-runtime.in"
TEST_IN = f"{PLATFORM}/requirements-test.in"
RUNTIME_LOCK = f"{PLATFORM}/requirements-runtime.txt"
TEST_LOCK = f"{PLATFORM}/requirements-test.txt"
OLD_REQUIREMENTS = f"{PLATFORM}/requirements.txt"
DOCKERFILES = (
    f"{PLATFORM}/agent-service/Dockerfile",
    f"{PLATFORM}/api-gateway/Dockerfile",
    # Phase 8.8A: the deployment slice's images carry the same contract —
    # the production image and the E2E variant both install ONLY the
    # hash-pinned runtime lock.
    f"{PLATFORM}/deployment_service/Dockerfile",
    f"{PLATFORM}/deployment_service/Dockerfile.e2e",
)
CI_WORKFLOW = ".github/workflows/ci.yml"

# The packages BOTH environments need: the versions in the two locks must
# be IDENTICAL (the "one compatible set" contract).
SHARED_PACKAGES = frozenset({
    "fastapi", "starlette", "anyio", "pydantic", "redis", "requests", "pyjwt",
    # Phase 8.8A: the deployment engine imports yaml at runtime, so
    # PyYAML is now a shared runtime dependency (both locks must agree).
    "pyyaml",
    # The deployment task module imports celery at import time and the
    # test environment exercises it (tests/test_deployment_dispatch_truth.py),
    # so the two locks must agree on celery too.
    "celery",
    # The Phase 6.5.1 release-identity carrier (backend/app/
    # release_identity.py) imports prometheus_client, and the ported
    # release-identity test loads that real module — both environments
    # must agree on the version.
    "prometheus-client",
})

# Every direct runtime dependency the containers must carry (the full set
# is deliberately kept — no silent slimming of the dependency surface).
RUNTIME_DIRECT = frozenset({
    "fastapi", "uvicorn", "requests", "sqlalchemy", "pydantic", "redis",
    "celery", "grpcio", "prometheus-client", "websockets", "structlog",
    "python-dotenv", "pyjwt",
    # Phase 8.8A: deployment engine / IaC validation import yaml.
    "pyyaml",
})

# Test/security-only tools that must be present in the test lock.
# (pyyaml moved to SHARED_PACKAGES with Phase 8.8A — it is a runtime
# dependency now, and the shared-parity check covers its presence.)
TEST_ONLY = frozenset({"httpx", "pytest"})

_PIN_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\\]+)")


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _parse_lock(path: Path) -> Dict[str, str]:
    """Map normalized package name -> pinned version from a pip-compile
    lock (only top-level pinned lines are considered)."""
    versions: Dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = _PIN_RE.match(line.strip())
        if m:
            versions[_norm(m.group(1))] = m.group(2)
    return versions


def _lock_has_hashes(path: Path) -> List[str]:
    """Every pinned package in the lock must carry >=1 sha256 hash."""
    violations = []
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        if _PIN_RE.match(lines[i].strip()):
            name = _PIN_RE.match(lines[i].strip()).group(1)
            has_hash = False
            j = i + 1
            while j < len(lines) and not _PIN_RE.match(lines[j].strip()):
                if "--hash=sha256:" in lines[j]:
                    has_hash = True
                    break
                j += 1
            if not has_hash:
                violations.append(f"{path.name}: package {name!r} has no sha256 hashes")
            i = j
        else:
            i += 1
    return violations


def check_dependency_contract(repo_root: Path) -> List[str]:
    """Source-level contract check; returns violation strings (empty = ok)."""
    v: List[str] = []

    runtime_lock_path = repo_root / RUNTIME_LOCK
    test_lock_path = repo_root / TEST_LOCK
    for rel in (RUNTIME_IN, TEST_IN):
        if not (repo_root / rel).exists():
            v.append(f"missing {rel} (the lock source of truth)")
    if (repo_root / OLD_REQUIREMENTS).exists():
        v.append("the retired broad requirements.txt reappeared — the "
                 "locks (requirements-runtime.txt / requirements-test.txt) "
                 "are the only dependency contract")

    if not runtime_lock_path.exists() or not test_lock_path.exists():
        v.append("missing hash-pinned lock(s): requirements-runtime.txt / "
                 "requirements-test.txt")
        return v

    for lock in (runtime_lock_path, test_lock_path):
        header = "\n".join(lock.read_text(encoding="utf-8").splitlines()[:8])
        if "pip-compile" not in header or "--generate-hashes" not in header:
            v.append(f"{lock.name}: not generated by pip-compile "
                     "--generate-hashes (hand-edited lock?)")
        v.extend(_lock_has_hashes(lock))

    runtime_versions = _parse_lock(runtime_lock_path)
    test_versions = _parse_lock(test_lock_path)

    # 1) Shared-package version parity: test == container.
    for pkg in sorted(SHARED_PACKAGES):
        rv, tv = runtime_versions.get(pkg), test_versions.get(pkg)
        if rv is None:
            v.append(f"parity: {pkg} missing from the runtime lock")
        if tv is None:
            v.append(f"parity: {pkg} missing from the test lock")
        if rv and tv and rv != tv:
            v.append(f"parity: {pkg} drift — runtime lock {rv} vs test lock "
                     f"{tv} (one compatible set required)")

    # 2) Full declared runtime set present in the runtime lock.
    for pkg in sorted(RUNTIME_DIRECT):
        if pkg not in runtime_versions:
            v.append(f"runtime lock: declared runtime dependency {pkg!r} "
                     "is missing")
    # 3) Test tools present in the test lock.
    for pkg in sorted(TEST_ONLY):
        if pkg not in test_versions:
            v.append(f"test lock: test-only dependency {pkg!r} is missing")

    # 4) Both service Dockerfiles install the runtime lock with hashes.
    for rel in DOCKERFILES:
        df = repo_root / rel
        if not df.exists():
            v.append(f"missing {rel}")
            continue
        dsrc = df.read_text(encoding="utf-8")
        if "COPY requirements-runtime.txt" not in dsrc:
            v.append(f"{rel}: must COPY the runtime lock "
                     "(requirements-runtime.txt)")
        if not re.search(
            r"pip install .*--require-hashes -r .*requirements-runtime\.txt",
            dsrc,
        ):
            v.append(f"{rel}: must install the runtime lock with "
                     "pip install --require-hashes")
        if re.search(r"pip install .*-r /app/requirements\.txt", dsrc):
            v.append(f"{rel}: still installs the retired broad "
                     "requirements.txt")

    # 5) Every CI Python install path uses --require-hashes on the test
    #    lock (10 jobs: the six Phase 8.7-C/D.1 gates plus the five
    #    Phase 8.8A deployment gates), and no plain install of the lock
    #    remains.
    ci = repo_root / CI_WORKFLOW
    if ci.exists():
        csrc = ci.read_text(encoding="utf-8")
        hashed = len(re.findall(
            r"pip install --require-hashes -r (?:\S+/)?requirements-test\.txt",
            csrc,
        ))
        if hashed != 10:
            v.append(f"ci.yml: expected exactly 10 hash-verified test-lock "
                     f"installs (found {hashed})")
        plain = re.findall(
            r"pip install (?!--require-hashes)(?:[^\n]* )?-r "
            r"(?:\S+/)?requirements-(?:test|runtime)\.txt",
            csrc,
        )
        if plain:
            v.append("ci.yml: a test/runtime lock is installed WITHOUT "
                     "--require-hashes (unpinned fallback)")
    return v


def check_dependency(repo_root: Path) -> List[str]:
    """Guard entry point (registered in ALL_GUARDS)."""
    return check_dependency_contract(repo_root)
